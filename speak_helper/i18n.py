CATALOGS: Mapping[str, Mapping[str, str]] = {"en": EN, "fr": FR}


class Translator(QObject):
    """Observable translator used by all presentation components."""

    language_changed = Signal(str)

    def __init__(self, config: Config, parent: QObject | None = None) -> None:
        super().__init__(parent)
        self._config = config
        self._language = config.language if config.language in SUPPORTED_LANGUAGES else "en"

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str, *, persist: bool = True) -> None:
        normalized = language if language in SUPPORTED_LANGUAGES else "en"
        if normalized == self._language:
            return
        self._language = normalized
        if persist:
            self._config.set("ui", "language", normalized)
            self._config.save()
        self.language_changed.emit(normalized)

    def text(self, key: str, **values: object) -> str:
        template = CATALOGS.get(self._language, EN).get(key, EN.get(key, key))
        try:
            return template.format(**values)
        except (KeyError, ValueError):
            return EN.get(key, key)
